export function checkoutLocale(value) {
  if (typeof value !== 'string') return null;
  const code = value.trim().toLowerCase().replaceAll('_', '-');
  const language = code === 'ckb' ? 'ku' : code.split('-')[0];
  return Object.hasOwn(checkoutLocales, language) ? language : null;
}
